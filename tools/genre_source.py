"""Curated genre data — the source of truth for assets/genre_graph.json.

Authored here rather than hand-written as JSON: 350 nodes of JSON is not
reviewable in a diff, and the compact tuple form below is. `build_genre_graph.py`
expands it; `validate_genre_graph.py` enforces the invariants.

Provenance
----------
Genre *names* follow MusicBrainz where a match exists (CC0, see
tools/musicbrainz_genres.txt). Lineage, tempo and era are facts researched from
public sources — Ishkur's Guide to Electronic Music for the electronic tree,
Beatport's commercial genre list for naming, and the usual DJ tempo references.
No third-party dataset is copied; energy/valence/mood are our own judgements.

Field guide
-----------
Each row is:

    (id, name, family, parents, aka, bpm, era, energy, valence, moods, near)

id       kebab-case, stable, the key everything else references
name     display name
family   one of FAMILIES
parents  ids this descends from; () for a family root
aka      alternative spellings and abbreviations users actually type
bpm      (low, high) typical tempo. The single most useful hard fact we have.
era      (start_year, end_year_or_None)
energy   0..1 arousal — how activating it is (Russell's circumplex)
valence  0..1 pleasantness — dark/tense at 0, bright/euphoric at 1
moods    mood ids this genre suits
near     ((id, weight), ...) sideways neighbours; parent/child links are implicit

Weights on `near` are "how likely is someone who likes A to accept B", not
similarity in the abstract. They are deliberately asymmetric-friendly: the graph
symmetrises them at build time by taking the max, because a one-way edge is
almost always an authoring oversight rather than a real claim.
"""

